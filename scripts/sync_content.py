ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/sync_content.py; edit content/ instead. -->'
EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp'}
COLUMNS = {'state', 'scientific_name', 'filename', 'location', 'country', 'city', 'description', 'title', 'cover_only',
           'latitude', 'longitude', 'order', 'include', 'id', 'category', 'coordinate_precision', 'location_method', 'country_album', 'atlas', 'fallback_filename', 'atlas_order'}


class ContentError(ValueError):
    pass


def read_json(path, default=None):
    if not path.exists() and default is not None:
        return copy.deepcopy(default)
    try:
        return json.loads(path.read_text(encoding='utf-8'))
    except (ValueError, OSError) as error:
        raise ContentError(f'{path}: {error}') from error


def slug(text):
    text = unicodedata.normalize('NFKD', text).encode('ascii', 'ignore').decode()
    result = re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')
    if not result:
        raise ContentError(f'Please use a folder name containing Latin letters or numbers: {text!r}')
    return result


def image_size(path):
    """Read JPEG/PNG/WebP dimensions without installing an image library."""
    with path.open('rb') as stream:
        head = stream.read(32)
        if head.startswith(b'\x89PNG\r\n\x1a\n') and len(head) >= 24:
            return struct.unpack('>II', head[16:24])
        if head[:2] == b'\xff\xd8':
            stream.seek(2)
            while True:
                byte = stream.read(1)
                if not byte:
                    break
                if byte != b'\xff':
                    continue
                marker = stream.read(1)
                while marker == b'\xff':
                    marker = stream.read(1)
                if not marker or marker in (b'\xd9', b'\xda'):
                    break
                if marker == b'\x00' or 0xD0 <= marker[0] <= 0xD8:
                    continue
                raw = stream.read(2)
                if len(raw) != 2:
                    break
                length = struct.unpack('>H', raw)[0]
                if length < 2:
                    break
                if marker[0] in {0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7,
                                  0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF}:
                    data = stream.read(5)
                    if len(data) == 5:
                        height, width = struct.unpack('>HH', data[1:5])
                        return width, height
                    break
                stream.seek(length - 2, 1)
        if head[:4] == b'RIFF' and head[8:12] == b'WEBP':
            if head[12:16] == b'VP8X':
                return (1 + int.from_bytes(head[24:27], 'little'),
                        1 + int.from_bytes(head[27:30], 'little'))
            if head[12:16] == b'VP8 ' and head[23:26] == b'\x9d\x01\x2a':
                width, height = struct.unpack('<HH', head[26:30])
                return width & 0x3FFF, height & 0x3FFF
            if head[12:16] == b'VP8L' and head[20:21] == b'\x2f':
                bits = int.from_bytes(head[21:25], 'little')
                return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    raise ContentError(f'{path}: cannot read image dimensions; export a JPEG, PNG, or WebP.')


def rows_for(folder):
    manifest = folder / 'photos.csv'
    listed, rows = set(), []
    if manifest.exists():
        with manifest.open(encoding='utf-8-sig', newline='') as stream:
            reader = csv.DictReader(stream)
            reader.fieldnames = [name.strip().lower() for name in (reader.fieldnames or [])]
            if len(reader.fieldnames) != len(set(reader.fieldnames)):
                raise ContentError(f'{manifest}: duplicate column names')
            if 'filename' not in reader.fieldnames:
                raise ContentError(f'{manifest}: missing filename column')
            unknown = set(reader.fieldnames) - COLUMNS
            if unknown:
                raise ContentError(f'{manifest}: unknown columns: {", ".join(sorted(unknown))}')
            for line, row in enumerate(reader, 2):
                if None in row:
                    raise ContentError(f'{manifest}:{line}: extra CSV cells; quote descriptions containing commas')
                row = {key: (value or '').strip() for key, value in row.items()}
                if not any(row.values()):
                    continue
                filename = row.get('filename', '')
                path = (folder / filename).resolve()
                if not filename or not path.is_relative_to(folder.resolve()):
                    raise ContentError(f'{manifest}:{line}: filename must stay inside this gallery folder')
                if path in listed:
                    raise ContentError(f'{manifest}:{line}: duplicate filename {filename}')
                listed.add(path)
                if row.get('fallback_filename'):
                    fallback = (folder / row['fallback_filename']).resolve()
                    if not fallback.is_relative_to(folder.resolve()):
                        raise ContentError(f"{manifest}:{line}: fallback leaves this folder")
                    listed.add(fallback)
                include = row.get('include', '').lower()
                if include not in {'', 'true', 'yes', '1', 'false', 'no', '0'}:
                    raise ContentError(f'{manifest}:{line}: include must be true or false')
                if include in {'false', 'no', '0'}:
                    continue
                if not path.is_file() or path.suffix.lower() not in EXTENSIONS:
                    raise ContentError(f'{manifest}:{line}: missing or unsupported photograph: {filename}')
                try:
                    order = float(row.get('order') or len(rows))
                    if not math.isfinite(order):
                        raise ValueError()
                except ValueError as error:
                    raise ContentError(f'{manifest}:{line}: order must be a finite number') from error
                rows.append((order, path, row))
    next_order = max((row[0] for row in rows), default=-1) + 1
    for path in sorted(folder.rglob('*')):
        if path.suffix.lower() not in EXTENSIONS or any(part.startswith('.') for part in path.relative_to(folder).parts):
            continue
        if not path.resolve().is_relative_to(folder.resolve()):
            raise ContentError(f'{path}: photograph symlink leaves the gallery folder')
        if path.is_file() and path.resolve() not in listed:
            rows.append((next_order, path.resolve(), {}))
            next_order += 1
    return sorted(rows, key=lambda row: row[0])


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding='utf-8') == text:
        return
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=path.parent,
                                     prefix=path.name + '.', suffix='.tmp', delete=False) as stream:
        stream.write(text)
        temporary = Path(stream.name)
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def sync(root=ROOT):
    """Build the entire site catalog from content/; legacy JSON is not an input."""
    root = Path(root).resolve()
    profiles, pages, cards, albums, slides, warnings = [], {}, [], {}, [], []
    reserved_pages = {'index.html', 'about.html', 'work.html', 'world-albums.html', 'photography.html', '404.html'}

    def page_name(value):
        if not isinstance(value, str) or not re.fullmatch(r'[a-z0-9-]+\.html', value) or value in reserved_pages:
            raise ContentError(f'Invalid generated page name: {value!r}')
        return value

    for kind, directory, config_file in [('gallery', 'galleries', 'gallery.json'),
                                          ('country', 'countries', 'album.json')]:
        parent = root / 'content' / directory
        if not parent.exists():
            continue
        for folder in sorted(parent.iterdir()):
            if not folder.is_dir() or folder.name.startswith('.'):
                continue
            if not folder.resolve().is_relative_to(root) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', folder.name):
                raise ContentError(f'{folder}: use a local folder with a lowercase, hyphenated name')
            config = read_json(folder / config_file, {})
            if not isinstance(config, dict):
                raise ContentError(f'{folder / config_file}: expected a JSON object')
            for key in ('title', 'name', 'category', 'description', 'label', 'cover', 'template', 'page'):
                if key in config and not isinstance(config[key], str):
                    raise ContentError(f'{folder / config_file}: {key} must be text')
            title = config.get('title' if kind == 'gallery' else 'name') or folder.name.replace('-', ' ').title()
            category = config.get('category') or title
            if kind == 'gallery' and category in {'All', 'Country Albums', 'Slideshow'}:
                raise ContentError(f'{folder}: {category!r} is a reserved category')
            if kind == 'gallery' and any(p['kind'] == kind and p['category'] == category for p in profiles):
                raise ContentError(f'Duplicate gallery category: {category}')
            default_page = ('gallery-' if kind == 'gallery' else 'country-') + folder.name + '.html'
            profiles.append(dict(kind=kind, folder=folder, config=config, title=title, category=category,
                                 page=page_name(config.get('page', default_page)), entries=[]))
    carousel_folder = root / 'content/carousel'
    profiles.append(dict(kind='carousel', folder=carousel_folder, config={}, title='Carousel',
                         category='Slideshow', entries=[]))
    countries = {p['title'].casefold(): p['title'] for p in profiles if p['kind'] == 'country'}
    known = {}
    location_file = root / 'content/locations.csv'
    if location_file.exists():
        with location_file.open(encoding='utf-8-sig', newline='') as stream:
            for row in csv.DictReader(stream):
                try:
                    lat, lng = float(row['latitude']), float(row['longitude'])
                    if not (-90 <= lat <= 90 and -180 <= lng <= 180):
                        raise ValueError()
                    known[(row['location'].casefold(), row['country'].casefold())] = (
                        lat, lng, row.get('coordinate_precision') or 'City')
                    countries.setdefault(row['country'].casefold(), row['country'])
                except (KeyError, ValueError) as error:
                    raise ContentError(f'{location_file}: invalid location reference row') from error

    baselines, hashes = {}, {}
    for profile in profiles:
        metadata = read_json(profile['folder'] / 'metadata.json', {})
        if not isinstance(metadata, dict) or any(not isinstance(v, dict) for v in metadata.values()):
            raise ContentError(f'{profile["folder"]}/metadata.json: expected records keyed by photo ID')
        for identity, baseline in metadata.items():
            baselines.setdefault(identity, baseline)
            if profile['kind'] != 'carousel' and baseline.get('_imageSha256'):
                hashes.setdefault(baseline['_imageSha256'], identity)

    candidates = {}
    def enabled(row, name, default):
        value = row.get(name, '').lower()
        if value not in {'', 'true', 'yes', '1', 'false', 'no', '0'}:
            raise ContentError(f'{name} must be true or false')
        return default if not value else value in {'true', 'yes', '1'}

    def record(profile, path, row):
        with path.open('rb') as stream:
            digest = hashlib.file_digest(stream, 'sha256').hexdigest()
        identity = row.get('id') or hashes.get(digest) or 'manual-' + digest[:24]
        if len(identity) > 200 or any(char in identity for char in '\r\n'):
            raise ContentError(f'{path}: invalid photo ID')
        baseline = baselines.get(identity, {})
        width, height = image_size(path)
        if not width or not height:
            raise ContentError(f'{path}: invalid image dimensions')
        photo = {k: copy.deepcopy(v) for k, v in baseline.items()
                 if not k.startswith('_') and k not in {
                     'src', 'largeSrc', 'width', 'height', 'albums', 'albumOrder', 'collections',
                     'collectionOrder', 'excluded', 'exclusionReason', 'cover', 'hero'}}
        default_country = profile['title'] if profile['kind'] == 'country' else ''
        country = row.get('country', baseline.get('country', default_country)) or default_country
        country = countries.setdefault(country.casefold(), country) if country else ''
        location = row.get('location', baseline.get('location', ''))
        description = row.get('description', baseline.get('description', ''))
        title = row.get('title') or description or baseline.get('title') or path.stem.replace('_', ' ')
        primary = quote(path.relative_to(root).as_posix(), safe='/')
        photo.update(id=identity, src=primary, width=width, height=height, title=title,
                     description=description, location=location, country=country,
                     scientificName=row.get('scientific_name', baseline.get('scientificName', '')),
                     city=row.get('city', baseline.get('city', '')),
                     state=row.get('state', baseline.get('state', '')),
                     category=row.get('category') or baseline.get('category') or profile['category'])
        fallback = row.get('fallback_filename')
        if fallback:
            fallback_path = (profile['folder'] / fallback).resolve()
            if not fallback_path.is_relative_to(profile['folder'].resolve()) or not fallback_path.is_file():
                raise ContentError(f'{path}: invalid fallback_filename')
            image_size(fallback_path)
            photo.update(src=quote(fallback_path.relative_to(root).as_posix(), safe='/'), largeSrc=primary)
        lat_text = row.get('latitude', baseline.get('lat', ''))
        lng_text = row.get('longitude', baseline.get('lng', ''))
        photo.pop('lat', None)
        photo.pop('lng', None)
        if lat_text != '' or lng_text != '':
            try:
                lat, lng = float(lat_text), float(lng_text)
                if not (-90 <= lat <= 90 and -180 <= lng <= 180):
                    raise ValueError()
            except (ValueError, TypeError) as error:
                raise ContentError(f'{path}: supply both valid latitude and longitude') from error
            changed_location = bool(baseline) and any([
                lat != baseline.get('lat'), lng != baseline.get('lng'),
                location != baseline.get('location'), country != baseline.get('country')])
            photo.update(lat=lat, lng=lng,
                         coordinatePrecision=row.get('coordinate_precision') or baseline.get('coordinatePrecision') or 'Landmark',
                         locationMethod='manual' if changed_location else (
                             row.get('location_method', baseline.get('locationMethod', 'manual'))))
        elif (location.casefold(), country.casefold()) in known:
            lat, lng, precision = known[(location.casefold(), country.casefold())]
            photo.update(lat=lat, lng=lng, coordinatePrecision=precision, locationMethod='known-place')
        else:
            photo.pop('coordinatePrecision', None)
            photo.pop('locationMethod', None)
        try:
            rank = float(row.get('atlas_order') or baseline.get('_atlasOrder', 1e12))
            if not math.isfinite(rank):
                raise ValueError()
        except (TypeError, ValueError) as error:
            raise ContentError(f'{path}: atlas_order must be a finite number') from error
        photo['atlasOrder'] = rank
        candidate = dict(photo=photo, baseline=baseline, digest=digest, path=path,
                         atlas=enabled(row, 'atlas', True) and not enabled(row, 'cover_only', False),
                         cover_only=enabled(row, 'cover_only', False),
                         country_album=enabled(row, 'country_album', True))
        candidates.setdefault(identity, []).append(candidate)
        hashes.setdefault(digest, identity)
        if candidate['cover_only']:
            profile.setdefault('cover_entries', []).append(identity)
        else:
            profile['entries'].append(identity)
        return candidate

    automatic_albums = []
    for profile in profiles:
        if not profile['folder'].exists():
            continue
        for index, (_, path, row) in enumerate(rows_for(profile['folder'])):
            item = record(profile, path, row)
            item['index'] = index
            if item['cover_only']:
                continue
            if profile['kind'] == 'country':
                automatic_albums.append((profile['title'], item['photo']['id']))
            elif item['country_album'] and item['photo']['country']:
                automatic_albums.append((item['photo']['country'], item['photo']['id']))
    settings = read_json(carousel_folder / 'settings.json', {})
    if not isinstance(settings, dict) or settings.get('mode', 'replace') != 'replace':
        raise ContentError('The carousel CSV is now the complete playlist; settings mode must be replace')
    if settings.get('mode') == 'replace' and not profiles[-1]['entries']:
        raise ContentError('The carousel needs at least one included photograph')

    resolved, thumbnail_sources = {}, {}
    scalar_fields = ('scientificName', 'title', 'description', 'location', 'country', 'city', 'state', 'lat', 'lng',
                     'coordinatePrecision', 'locationMethod', 'atlasOrder')
    for identity, versions in candidates.items():
        baseline = baselines.get(identity, {})
        photo = copy.deepcopy(versions[0]['photo'])
        for key in scalar_fields:
            original = baseline.get('_atlasOrder', 1e12) if key == 'atlasOrder' else baseline.get(key, '' if key in {'scientificName', 'description', 'location', 'country', 'city', 'state'} else None)
            values = [version['photo'].get(key) for version in versions]
            changed = [value for value in values if value != original] if baseline else values
            distinct = []
            for value in changed:
                if value not in distinct:
                    distinct.append(value)
            if len(distinct) > 1:
                raise ContentError(f'{identity}: conflicting {key} edits across CSVs; make the changed values match')
            value = distinct[0] if distinct else photo.get(key)
            if value is None:
                photo.pop(key, None)
            else:
                photo[key] = value
        original_hash = baseline.get('_imageSha256')
        changed_images = {v['digest'] for v in versions if not original_hash or v['digest'] != original_hash}
        if len(changed_images) > 1:
            raise ContentError(f'{identity}: conflicting image replacements across gallery folders')
        selected = next((v for v in versions if v['digest'] in changed_images), versions[0])
        thumbnail_sources[identity] = dict(path=selected['path'], digest=selected['digest'])
        for key in ('src', 'largeSrc', 'width', 'height'):
            if key in selected['photo']:
                photo[key] = selected['photo'][key]
            else:
                photo.pop(key, None)
        if photo.get('locationMethod') == 'manual' and baseline and (
                photo.get('lat') != baseline.get('lat') or photo.get('lng') != baseline.get('lng')
                or photo.get('location') != baseline.get('location')):
            photo.update(locationSources=[], locationConfidence='user',
                         locationEvidence='Location supplied through the photo CSV.')
        photo.update(atlas=any(v['atlas'] for v in versions), coverOnly=all(v['cover_only'] for v in versions), collections=[], collectionOrder={},
                     albums=[], albumOrder={})
        resolved[identity] = photo

    def cover_for(profile):
        cover_name = profile['config'].get('cover', '')
        if cover_name:
            path = (profile['folder'] / cover_name).resolve()
            matches = [identity for identity in profile['entries'] + profile.get('cover_entries', []) if any(v['path'] == path for v in candidates[identity])]
            if matches:
                return resolved[matches[0]]
            # An excluded/deleted cover falls back to the first remaining photo.
            warnings.append(f'{profile["folder"].relative_to(root)}: cover is not included; using the first photo.')
        return resolved[profile['entries'][0]]

    def render_page(profile, values, default_template):
        name = profile['page']
        if name in pages:
            raise ContentError(f'Duplicate generated page: {name}')
        template = root / profile['config'].get('template', default_template)
        if not template.resolve().is_relative_to((root / 'templates').resolve()):
            raise ContentError(f'{profile["folder"]}: template must stay in templates/')
        pages[name] = Template(template.read_text()).substitute(
            {key: html.escape(str(value), quote=True) for key, value in values.items()})

    for profile in profiles:
        if not profile['entries']:
            continue
        config = profile['config']
        if profile['kind'] == 'gallery':
            category, title = profile['category'], profile['title']
            for index, identity in enumerate(profile['entries']):
                photo = resolved[identity]
                photo['collections'].append(category)
                photo['collectionOrder'][category] = index
            cover = cover_for(profile)
            label = config.get('label', 'PHOTOGRAPHS / ' + title.upper())
            description = config.get('description', '')
            values = dict(title=title, category=category, description=description, label=label,
                          cover=cover.get('largeSrc') or cover['src'], cover_id=cover['id'],
                          cover_alt=cover['title'],
                          cover_place=', '.join(filter(None, (cover['title'], cover.get('city') or cover['location'], cover['country']) if category == 'World Landmarks' else (cover['title'], cover['city']) if cover.get('city') else (cover['location'], cover['country']))))
            render_page(profile, values, 'templates/manual-gallery.html')
            if 'featured' in config and not isinstance(config['featured'], bool):
                raise ContentError(f'{profile["folder"]}: featured must be true or false')
            try:
                feature_order = float(config.get('featured_order', 1e12))
                if not math.isfinite(feature_order):
                    raise ValueError()
            except (TypeError, ValueError) as error:
                raise ContentError(f'{profile["folder"]}: featured_order must be numeric') from error
            cards.append(dict(category=category, title=title, displayTitle=title, description=description,
                              label=label, page=profile['page'], photo=cover['id'],
                              featured=config.get('featured', True), order=feature_order))
        elif profile['kind'] == 'country':
            name = profile['title']
            if name in albums:
                raise ContentError(f'Duplicate country album: {name}')
            cover = cover_for(profile)
            albums[name] = dict(name=name, page=profile['page'], count=0, coverPhoto=cover['id'],
                                cover=cover.get('largeSrc') or cover['src'], coverPosition=profile['config'].get('cover_position', '50% 50%'), photoIds=list(profile['entries']))
            render_page(profile, dict(country=name), 'templates/manual-country.html')
        else:
            slides.extend(resolved[identity] for identity in profile['entries'])

    for country, identity in automatic_albums:
        if country not in albums:
            profile = dict(title=country, page=page_name('country-' + slug(country) + '.html'),
                           config={}, folder=root / 'content/countries')
            photo = resolved[identity]
            albums[country] = dict(name=country, page=profile['page'], count=0, coverPhoto=identity,
                                   cover=photo.get('largeSrc') or photo['src'], photoIds=[])
            render_page(profile, dict(country=country), 'templates/manual-country.html')
        if identity not in albums[country]['photoIds']:
            albums[country]['photoIds'].append(identity)
    for name, album in albums.items():
        for index, identity in enumerate(album['photoIds']):
            resolved[identity]['albums'].append(name)
            resolved[identity]['albumOrder'][name] = index
        album['count'] = len(album['photoIds'])
    for photo in resolved.values():
        if photo['atlas'] and ('lat' not in photo or not photo.get('location')):
            warnings.append(f'{photo["id"]}: no pin yet; add coordinates or a known location/country.')
    try:
        thumbnail_files = attach_thumbnails(root, resolved, thumbnail_sources)
    except ThumbnailError as error:
        raise ContentError(str(error)) from error
    data = dict(version=3, photos=sorted(resolved.values(), key=lambda p: p['atlasOrder']),
                galleries=sorted(cards, key=lambda c: c['order']),
                countryAlbums=sorted(albums.values(), key=lambda a: a['name']),
                carousel=slides, carouselMode='replace')
    if (root / 'templates/home.html').exists():
        if not slides:
            raise ContentError('The homepage carousel needs at least one included photo')
        first = slides[0]
        pages['index.html'] = Template((root / 'templates/home.html').read_text()).substitute(
            hero_src=html.escape(first.get('largeSrc') or first['src'], quote=True),
            hero_alt=html.escape(first['title'], quote=True),
            hero_place=html.escape(', '.join(filter(None, (first['location'], first['country'])))))
    previous_manifest = read_json(root / 'generated/pages.json', [])
    for name in pages:
        path = root / name
        if path.exists() and 'Generated by scripts/sync_content.py;' not in path.read_text():
            raise ContentError(f'Refusing to overwrite a hand-edited page: {name}')
    for name, text in pages.items():
        atomic_write(root / name, text)
    atomic_write(root / 'generated/content.json', json.dumps(clean_catalog(data), ensure_ascii=False, indent=2) + '\n')
    for name in previous_manifest:
        if (isinstance(name, str) and re.fullmatch(r'[a-z0-9-]+\.html', name)
                and name not in reserved_pages and name not in pages and (root / name).is_file()
                and MARKER in (root / name).read_text()):
            (root / name).unlink()
    atomic_write(root / 'generated/pages.json', json.dumps(sorted(pages), indent=2) + '\n')
    write_preview_routes(root, pages)
    prune_thumbnails(root, thumbnail_files)
    return dict(photos=sum(p['atlas'] for p in resolved.values()), galleries=len(cards),
                carousel=len(slides), warnings=warnings)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    try:
        result = sync(args.root)
    except (ContentError, OSError) as error:
        print(f'Content sync failed: {error}', file=sys.stderr)
        return 1
    print(f'Synced {result["photos"]} atlas photos, {result["galleries"]} galleries, {result["carousel"]} carousel photos.')
    for warning in result['warnings']:
        print('Note: ' + warning)
    return 0


if __name__ == '__main__':
    sys.exit(main())
